#!/usr/bin/env bash
# Re-sync the vendored PocketShell doodle constants into DoodleReference.generated.cs.
#
# Source of truth (read-only): ~/git/pocketshell-core
#   packages/ui/src/app/doodleModel.ts          PENS, WIDTHS
#   src/shared/doodleGeometry.ts                 ARROW, TEXT, SNAP_RADIANS
#   packages/ui/src/styles.css or tokens.css     colour / type / layout tokens
#   packages/ui/src/components/AppIcon.vue       Feather 4.29 icon paths
#   packages/ui/src/app/components/DoodleCanvas.vue footer/toolbar strings
#
# Usage:
#   scripts/sync-doodle-reference.sh            regenerate the .generated.cs
#   scripts/sync-doodle-reference.sh --check     fail if the committed file is stale
set -euo pipefail

CORE="${POCKETSHELL_CORE:-$HOME/git/pocketshell-core}"
OUT="src/Annotator/DoodleReference.generated.cs"
TMP="$(mktemp)"

python3 - "$CORE" > "$TMP" <<'PY'
import re, sys

core = sys.argv[1]

def read(rel):
    with open(f"{core}/{rel}", encoding="utf-8") as f:
        return f.read()

model = read("packages/ui/src/app/doodleModel.ts")
geo = read("src/shared/doodleGeometry.ts")
try:
    tokens = read("packages/ui/src/tokens.css")
except FileNotFoundError:
    tokens = read("packages/ui/src/styles.css")
icons = read("packages/ui/src/components/AppIcon.vue")

def token(name):
    m = re.search(rf"--{re.escape(name)}:\s*([^;]+);", tokens)
    if not m:
        raise SystemExit(f"token --{name} not found")
    return m.group(1).strip()

def geo_num(obj, field):
    m = re.search(rf"{re.escape(obj)}\s*=\s*\{{(.*?)\}}", geo, re.S)
    body = m.group(1)
    m2 = re.search(rf"{re.escape(field)}\s*:\s*([^,/\n]+)", body)
    return m2.group(1).strip()

def width_list():
    m = re.search(r"WIDTHS\s*=\s*\[([^\]]+)\]", model)
    return [w.strip() for w in m.group(1).split(",")]

widths = width_list()
pens = ["--error", "--warning", "--success", "--accent", "--agent", "--fg"]

def icon(name):
    m = re.search(rf"^  '{re.escape(name)}':\s*\{{\s*paths:\s*\[(.*?)\]", icons, re.S | re.M)
    if not m:
        m = re.search(rf"^  {re.escape(name)}:\s*\{{\s*paths:\s*\[(.*?)\]", icons, re.S | re.M)
    paths = re.findall(r"'((?:[^'\\]|\\.)*)'", m.group(1))
    return paths

icon_names = ["edit-2", "minus", "arrow-right", "square", "circle", "type", "rotate-ccw", "trash-2"]
icon_block = []
for n in icon_names:
    paths = icon(n)
    joined = ", ".join('"' + p + '"' for p in paths)
    icon_block.append(f'        {{ "{n}", new[] {{ {joined} }} }},')

cs = f"""// <auto-generated by scripts/sync-doodle-reference.sh — do not edit by hand.>
// Vendored PocketShell doodle constants. Source of truth:
//   pocketshell-core packages/ui/src/app/doodleModel.ts (PENS, WIDTHS)
//   pocketshell-core src/shared/doodleGeometry.ts (ARROW, TEXT, SNAP)
//   pocketshell-core packages/ui/src/tokens.css (colour/type/layout tokens)
//   pocketshell-core packages/ui/src/components/AppIcon.vue (Feather 4.29 icon paths, MIT)
// Re-run scripts/sync-doodle-reference.sh after pulling pocketshell-core.
namespace Annotator;

internal static class DoodleReference
{{
    // --error --warning --success --accent --agent --fg (doodleModel.PENS)
    public static readonly string[] PenTokens = {{ "--error", "--warning", "--success", "--accent", "--agent", "--fg" }};
    public static readonly string[] PenHex = {{ "{token('error')}", "{token('warning')}", "{token('success')}", "{token('accent')}", "{token('agent')}", "{token('fg')}" }};
    public static readonly string[] PenNames = {{ "error", "warning", "success", "accent", "agent", "fg" }};

    // WIDTHS (doodleModel.WIDTHS), default = middle rung
    public static readonly float[] Weights = {{ {widths[0]}f, {widths[1]}f, {widths[2]}f }};
    public const int DefaultWeightIndex = 1;

    // ARROW (doodleGeometry.ARROW)
    public const float HeadRatio = 4;
    public const float MaxHeadFraction = 0.6f;
    public const double Spread = System.Math.PI / 7;
    public const float MinLength = 2;

    // TEXT (doodleGeometry.TEXT)
    public const float TextSizeRatio = 8;
    public const float TextMinSize = 36;
    public const float LineHeightRatio = 1.3846f;
    public const float TextEdgePadding = 0.5f;
    public const float TextHitPadding = 0.25f;

    // Tokens (tokens.css)
    public const string Bg = "{token('bg')}";
    public const string Surface2 = "{token('surface-2')}";
    public const string Fg = "{token('fg')}";
    public const string FgSecondary = "{token('fg-secondary')}";
    public const string Border = "{token('border')}";
    public const string BorderStrong = "{token('border-strong')}";
    public const string Accent = "{token('accent')}";
    public const string OnAccent = "{token('on-accent')}";
    public const string Error = "{token('error')}";
    public const string DisabledOpacity = "{token('disabled-opacity')}";
    public const string FontUi = "{token('font-ui')}";
    public const int ControlH = 28;
    public const int ControlHSm = 24;
    public const int RadiusSm = 4;
    public const int RadiusMd = 6;
    public const int Sp1 = 4;
    public const int Sp2 = 8;

    // Feather 4.29 paths (AppIcon.vue GEOMETRY), 24x24 grid, stroke 2, round caps/joins.
    public static readonly System.Collections.Generic.Dictionary<string, string[]> IconPaths = new()
    {{
{chr(10).join(icon_block)}
    }};
}}
"""
sys.stdout.write(cs)
PY

if [ "${1:-}" = "--check" ]; then
  if ! diff -q "$TMP" "$OUT" > /dev/null 2>&1; then
    echo "DoodleReference.generated.cs is stale. Run scripts/sync-doodle-reference.sh" >&2
    rm -f "$TMP"
    exit 1
  fi
  rm -f "$TMP"
  echo "DoodleReference.generated.cs is in sync."
else
  mv "$TMP" "$OUT"
  echo "Wrote $OUT"
fi
